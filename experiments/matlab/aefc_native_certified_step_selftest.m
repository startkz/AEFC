function aefc_native_certified_step_selftest
% CONDITIONAL validation against a synthetic 12-state / four-sensor system.
% A piecewise-linear physical interpolation between sampled states is
% assumed, making convex safe-box intersample inclusion meaningful only
% for this artificial test. No native IEEE39 property is inferred.
rng(20261125);
n=12;m=4;p=4;
A=0.92*eye(n);B=0.018*randn(n,m);H=zeros(p,n);
for j=1:p,H(j,3*j-2)=1;end
mdl=struct('A',A,'B',B,'H',H,'c',zeros(n,1), ...
    'w_bound',0.002*ones(n,1), ...
    'input_attack_bound',0.010*ones(m,1),...
    'sensor_error',0.001*ones(p,1), ...
    'safe_lower',-0.30*ones(n,1), ...
    'safe_upper',0.30*ones(n,1), ...
    'input_lower',-0.20*ones(m,1), ...
    'input_upper',0.20*ones(m,1), ...
    'full_network_variables_covered',true, ...
    'safety_predicates_all_covered',true, ...
    'full_state_dynamics_verified',true, ...
    'measurement_map_verified',true, ...
    'intersample_reachability_verified',true, ...
    'verified_emergency_policy',true);
opts=struct('max_passes',4,'roundoff_inflation',1e-11);
released=0;
for seed=1:100
    state=struct('center',zeros(n,1),'error',0.03*ones(n,1),'coverage_verified',true);
    truth=(2*rand(n,1)-1).*state.error;
    prev=zeros(m,1);
    for t=1:8
        a=(2*rand(m,1)-1).*mdl.input_attack_bound;
        w=(2*rand(n,1)-1).*mdl.w_bound;
        truth=mdl.A*truth+mdl.B*(prev+a)+w;
        y=mdl.H*truth+(2*rand(p,1)-1).*mdl.sensor_error;
        proposed=0.10*(2*rand(m,1)-1);
        [command,next,diag]=aefc_native_certified_execution_step( ...
            state,mdl,prev,y,proposed,zeros(m,1),opts);
        assert(diag.certified && diag.full_state_covered && diag.intersample_safe, ...
            'AEFC:CertifiedStepTest','Synthetic conservative candidate unjustifiably rejected');
        assert(all(abs(truth-next.center)<=next.error+1e-8),...
            'AEFC:CertifiedStepTest','True synthetic state escaped full-state observer');
        assert(all(command>=mdl.input_lower+mdl.input_attack_bound-1e-8) && ...
               all(command<=mdl.input_upper-mdl.input_attack_bound+1e-8), ...
            'AEFC:CertifiedStepTest','Input bound failed');
        assert(isfinite(diag.margin) && diag.margin>=-1e-10);
        state=next;prev=command;released=released+1;
    end
end
mdl.intersample_reachability_verified=false;
[command,~,diag]=aefc_native_certified_execution_step( ...
    state,mdl,prev,y,zeros(m,1),zeros(m,1),opts);
assert(all(command==0) && diag.status==-210 && ~diag.certified,...
    'AEFC:CertifiedStepTest','Unproven hold interval must fail closed');
mdl.intersample_reachability_verified=true;
mdl.full_network_variables_covered=false;
[command,~,diag]=aefc_native_certified_execution_step( ...
    state,mdl,prev,y,zeros(m,1),zeros(m,1),opts);
assert(all(command==0) && diag.status==-210 && ~diag.certified,...
    'AEFC:CertifiedStepTest','Incomplete native state must fail closed');
fprintf('FULL-STATE EXECUTION CHAIN: %d certified synthetic samples; missing hold/full-network proof blocked. Real IEEE39 not certified.\\n',released);
end
