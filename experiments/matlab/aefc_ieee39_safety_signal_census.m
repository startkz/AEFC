function aefc_ieee39_safety_signal_census
% Genuine MathWorks IEEE39 R2024b structural discovery only.
% Enumerates candidates for voltages, bus algebraic variables, line currents,
% branch powers and machine angles without declaring a sensor trusted from
% a block NAME. Identification requires causal probe and signal calibration.
repo=pwd;
out=fullfile(repo,'results','ieee39_safety_mapping');
if ~exist(out,'dir'),mkdir(out);end
[model,source]=aefc_ieee39_load_official;
blocks=find_system(model,'LookUnderMasks','all','FollowLinks','on', ...
    'Type','Block');
categories={'generator_speed','rotor_angle','bus_voltage','branch_power',...
    'branch_current','algebraic_grid','physical_measurement_other'};
seen=struct;
for k=1:numel(categories)
    seen.(categories{k})=0;
end
entries=struct('path',{},'name',{},'block_type',{},'category',{}, ...
    'output_ports',{},'output_signal_label',{},'candidate_only',{},...
    'online_authenticated_sensor',{},'causal_measurement_validation',{});
for k=1:numel(blocks)
    path=blocks{k};
    name='';type='';nOut=0;labels={};
    try,name=char(get_param(path,'Name'));catch,end
    try,type=char(get_param(path,'BlockType'));catch,end
    try
        ph=get_param(path,'PortHandles');
        if isfield(ph,'Outport'),nOut=numel(ph.Outport);end
        for j=1:nOut
            lname='';
            try
                h=get_param(ph.Outport(j),'Line');
                if h~=-1,lname=char(get_param(h,'Name'));end
            catch
            end
            labels{j}=lname; %#ok<AGROW>
        end
    catch
    end
    if nOut<1,continue;end
    combined=lower([path ' ' name ' ' strjoin(labels,' ')]);
    inGrid=contains(lower(path),'/grid/');
    inGenerator=contains(lower(path),'/generators/');
    category='';
    if inGenerator && (contains(combined,'rotor speed') || ...
            contains(combined,'speed measurement') || ...
            endsWith(lower(name),'/w') || strcmp(lower(name),'w'))
        category='generator_speed';
    elseif inGenerator && (contains(combined,'rotor angle') || ...
            strcmp(lower(name),'delta') || contains(combined,'electrical angle'))
        category='rotor_angle';
    elseif inGrid && (contains(combined,'voltage measurement') || ...
            contains(combined,'voltage sensor') || contains(combined,'vrms') || ...
            contains(combined,'vmag') || contains(combined,'vabc'))
        category='bus_voltage';
    elseif inGrid && (contains(combined,'power measurement') || ...
            contains(combined,'power flow') || contains(combined,'pflow') || ...
            contains(combined,'pmeas'))
        category='branch_power';
    elseif inGrid && (contains(combined,'current sensor') || ...
            contains(combined,'current measurement') || ...
            contains(combined,'iabc') || contains(combined,'irms'))
        category='branch_current';
    elseif inGrid && (contains(combined,'solver configuration') || ...
            contains(combined,'algebraic') || contains(combined,'powergui'))
        category='algebraic_grid';
    elseif (contains(combined,'measurement') || contains(combined,'sensor')) ...
            && (inGrid || inGenerator)
        category='physical_measurement_other';
    end
    if isempty(category),continue;end
    e=struct('path',path,'name',name,'block_type',type, ...
        'category',category,'output_ports',nOut, ...
        'output_signal_label',{labels},'candidate_only',true, ...
        'online_authenticated_sensor',false, ...
        'causal_measurement_validation',false);
    entries(end+1)=e; %#ok<AGROW>
    seen.(category)=seen.(category)+1;
end
report=struct('model',model,'original_model_source',source, ...
    'scanned_blocks',numel(blocks), ...
    'candidates_by_category',seen, ...
    'entries',entries, ...
    'required_bus_voltage_channels',39, ...
    'verified_bus_voltage_channels',0, ...
    'verified_branch_thermal_channels',0, ...
    'verified_rotor_angle_channels',0, ...
    'verified_full_state_estimator_error_set',false, ...
    'verified_DAE_reachable_set',false, ...
    'verified_inter_sample_tube',false, ...
    'qualified_as_complete_IEEE39_safety_observation',false, ...
    'important',['Block-name discovery supplies candidates only; ' ...
     'no physical sensor, signal identity, all-bus coverage or online ' ...
     'authentication is established by the result']);
f=fullfile(out,'native_safety_signal_census.json');
fid=fopen(f,'w');assert(fid>0,'AEFC:CensusIO','Cannot save census');
fwrite(fid,jsonencode(report,'PrettyPrint',true),'char');
fwrite(fid,sprintf('\n'),'char');fclose(fid);
fprintf('IEEE39 native safety signal candidates: %d from %d blocks; certified 39-bus voltage coverage=FALSE.\\n', ...
    numel(entries),numel(blocks));
close_system(model,0);
end
