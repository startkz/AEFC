classdef AEFCNativeOnlineRecoveryController < matlab.System
% AEFCNativeOnlineRecoveryController: independently instrumented full native controller.
% Precommitted commissioning checkpoint and message-consistency detector; no
% attack-start/end flag, malicious identity label, or clean shadow used by recovery.
% RecoveryMode 0=baseline, 1=quarantine, 2=checkpoint rollback, 3=online consistent-proxy relearning.
% Logs real four-parameter federated deployment plus offline same-operator
% clean-input shadow using matched actual plant observations.
% Supplemental-only controller used for attack-intensity, targeted gate-stress,
% and one-at-a-time parameter sensitivity experiments. Default values reproduce
% the authoritative AEFCNativeController behavior; the main 560-run experiment
% is never modified or regenerated by this class.
%
% MethodCode: 1 FedRL, 2 RobustAgg, 3 AEFC-no-PATBU, 4 AEFC-no-Gate,
%             5 AEFC-no-TGOPA, 6 AEFC-no-Shield, 7 AEFC-Full.
% ScenarioCode: 1 clean, 2 knowledge, 3 physical, 4 joint.

properties(Nontunable)
    ConfigPath = 'configs/ieee39_joint20.json'
    MappingPath = 'results/ieee39_r2024b/interface_mapping.json'
end

properties
    MethodCode = 7
    ScenarioCode = 4
    Seed = 0
    AttackScale = 1.0
    ProposalStressAlpha = 0.0
    RhoMaxOverride = -1.0
    QMinOverride = -1.0
    TrustRegionOverride = -1.0
    RecoveryMode = 0
end

properties(Access=private)
    cfg
    mapping
    B
    Bn
    center
    scale
    belief
    cleanBelief
    theta
    stepCount
    thetaShadow
    beliefShadow
    legacyShadow
    checkpointTheta
    checkpointValid
    alarmLatched
    quietRun
    recoveryPhase
    lastRollback
    teacherTheta
    teacherBelief
    teacherLegacy
    teacherAccepted
    teacherGate
    inlierCount
end

methods(Access=protected)
    function setupImpl(obj,~)
        obj.loadRuntimeConfig();
        obj.resetRuntimeState();
    end

    function resetImpl(obj)
        obj.ensureRuntimeState();
        obj.resetRuntimeState();
    end

    function [uShield,uPost,diagOut]=stepImpl(obj,obsPhysical)
        obj.ensureRuntimeState();

        obsPhysical=double(obsPhysical(:));
        if numel(obsPhysical)~=4
            obsPhysical=obsPhysical(1:min(4,numel(obsPhysical)));
            obsPhysical(end+1:4,1)=0;
        end
        t=obj.stepCount;
        mc=round(double(obj.MethodCode));
        sc=round(double(obj.ScenarioCode));
        attackScale=max(0,double(obj.AttackScale));
        stressAlpha=min(max(double(obj.ProposalStressAlpha),0),1);
        rhoMax=double(obj.cfg.gate.rho_max);
        if double(obj.RhoMaxOverride)>0, rhoMax=double(obj.RhoMaxOverride); end
        qMin=double(obj.cfg.gate.q_min);
        if double(obj.QMinOverride)>=0, qMin=double(obj.QMinOverride); end
        trustRegion=double(obj.cfg.adaptation.trust_region);
        if double(obj.TrustRegionOverride)>0, trustRegion=double(obj.TrustRegionOverride); end

        [physicalOn,knowledgeOn]=obj.scenarioFlags(sc);
        attackActive=t>=obj.cfg.attack_start_step && t<=obj.cfg.attack_end_step;
        physicalActive=physicalOn && attackActive && attackScale>0;
        knowledgeActive=knowledgeOn && attackActive && attackScale>0;

        zPhysical=(obsPhysical-obj.center)./obj.scale;
        obsReceived=zPhysical;
        if physicalActive
            obsReceived=obsReceived + attackScale*obj.cfg.observation_attack_fraction_of_scale*obj.detNoise(t,97);
        end

        nClients=obj.cfg.clients; f=obj.cfg.byzantine_clients;
        updates=zeros(4,nClients); evidence=zeros(4,nClients);
        cleanUpdates=zeros(4,nClients); cleanEvidence=zeros(4,nClients);
        provenance=true(1,nClients); ages=zeros(1,nClients);
        for j=1:nClients
            g=0.65*zPhysical + 0.15*obj.detNoise(t,10+j);
            ev=-0.55*zPhysical + 0.08*obj.detNoise(t,30+j);
            cleanUpdates(:,j)=g;
            cleanEvidence(:,j)=ev;
            if knowledgeActive && j<=f
                g=-(obj.cfg.model_replacement_scale*attackScale)*g + ...
                    (0.8*attackScale)*obj.detNoise(t,50+j);
                ev=(obj.cfg.model_replacement_scale*attackScale)*ev + 0.6*attackScale;
                provenance(j)=false;
                ages(j)=obj.cfg.stale_delay;
            end
            updates(:,j)=g;
            evidence(:,j)=ev;
        end

        if mc==1
            agg=mean(updates,2); trust=0.5;
        else
            agg=obj.robustAggregate(updates,f,obj.cfg.common_support_k);
            trust=0.5;
        end

        cleanK=mean(evidence(:,provenance),2);
        if isempty(cleanK), cleanK=zeros(4,1); end
        obj.cleanBelief=0.72*obj.cleanBelief + 0.20*zPhysical + 0.08*cleanK;

        if any(mc==[1 2 3])
            beliefNow=obsReceived;
        else
            weights=zeros(1,nClients); weighted=zeros(4,nClients);
            for j=1:nClients
                % Online client-report consistency, NOT oracle adversary identity.
                if true
                    ageTerm=exp(-obj.cfg.patbu.beta_age*ages(j));
                    residual=norm(evidence(:,j)-obj.belief,2);
                    consistency=1/(1+(residual/max(obj.cfg.patbu.residual_scale,1e-9))^2);
                    weights(j)=ageTerm*consistency;
                end
                weighted(:,j)=weights(j)*evidence(:,j);
            end
            k=obj.trimmedMean(weighted,f);
            beliefNow=obj.cfg.patbu.lambda_b*obj.belief + ...
                obj.cfg.patbu.obs_gain*obsReceived + obj.cfg.patbu.knowledge_gain*k;
            beliefNow=min(max(beliefNow,-2),2);
            trust=min(max(mean(weights),0),1);
            obj.belief=beliefNow;
        end

        beliefDist=norm(beliefNow-obj.cleanBelief,2);
        proposal=-0.20*(obj.Bn')*beliefNow + 1.5*obj.theta;
        proposal=obj.clipVec(proposal,obj.cfg.action_limit);

        % Targeted unsafe learned-proposal stress is injected before the gate,
        % not at the plant. At alpha=1 the pre-gate predicted state is driven
        % well beyond the normalized safe boundary, while the downstream
        % shield and post-shield attack model remain unchanged.
        if stressAlpha>0 && attackActive
            sgn=sign(obj.detNoise(t,401)); sgn(sgn==0)=1;
            target=(double(obj.cfg.normalized_safe_limit)+0.75)*sgn;
            uUnsafe=pinv(obj.Bn)*(target-beliefNow);
            proposal=(1-stressAlpha)*proposal + stressAlpha*uUnsafe;
        end

        pred=beliefNow + obj.Bn*proposal;
        safetyShortfall=max(0,max(abs(pred))-0.85);
        recoveryShortfall=max(0,max(abs(beliefNow))-obj.cfg.normalized_recovery_limit);
        % Online authorization never reads experiment-only cleanBelief.
        uncertainty=min(1,norm(obsReceived-beliefNow,2));
        risk=0.62*safetyShortfall + 0.16*recoveryShortfall + ...
            0.14*uncertainty + 0.08*(1-trust);
        gateAllowed=(risk <= rhoMax-obj.cfg.gate.risk_margin) && (trust>=qMin);
        dangerous=max(abs(pred))>obj.cfg.normalized_safe_limit;
        if any(mc==[1 2 4])
            gateAllowed=true;
        end
        if ~gateAllowed, proposal=-0.05*(obj.Bn')*beliefNow; end

        thetaBefore=obj.theta;
        % A local detector sees only the seven RECEIVED evidence vectors.
        % Threshold 0.35 fixed from PREVIOUS 0:19 exploratory traces;
        % this new validation uses disjoint 20:39 seed values.
        evMedian=median(evidence,2);
        reportScatter=max(sqrt(sum((evidence-evMedian).^2,1)));
        reportSuspicious=reportScatter>0.35;
        obj.lastRollback=0.0;
        obj.teacherAccepted=false;
        obj.teacherGate=false;
        obj.inlierCount=0;
        if t==10 && ~obj.checkpointValid && ~reportSuspicious
            % Commissioning-only trust assumption; locally isolated snapshot.
            % Not a cryptographic signature or authenticated optimum.
            obj.checkpointTheta=obj.theta;
            obj.checkpointValid=true;
        end
        if obj.checkpointValid && reportSuspicious && obj.RecoveryMode>0
            obj.alarmLatched=true;
            obj.recoveryPhase=1;
            obj.quietRun=0;
        end
        g=agg; gn=norm(g,2);
        if gn>obj.cfg.adaptation.clip_norm
            g=g*(obj.cfg.adaptation.clip_norm/gn);
        end
        delta=-obj.cfg.adaptation.eta*trust*g;
        dn=norm(delta,2);
        if dn>trustRegion
            delta=delta*(trustRegion/dn);
        end
        candidate=obj.theta+delta;
        valBefore=norm(beliefNow,2)+0.08*norm(obj.theta,2);
        valAfter=norm(beliefNow,2)+0.08*norm(candidate,2);
        adaptAccepted=trust>=qMin && gateAllowed && ...
            valAfter<=valBefore+obj.cfg.adaptation.validation_slack;
        if any(mc==[1 2 5])
            obj.theta=obj.theta-0.12*agg; adaptAccepted=true;
        elseif adaptAccepted
            obj.theta=candidate;
        end
        % The authorization and adaptation decision above is the ORIGINAL
        % TGOPA output; quarantine and rollback operate AFTER it.
        if any(double(obj.RecoveryMode)==[1 2]) && obj.checkpointValid && obj.alarmLatched
            if obj.recoveryPhase==1
                obj.theta=thetaBefore; % isolate any learned candidate
                adaptAccepted=false;
                if ~reportSuspicious
                    obj.quietRun=obj.quietRun+1;
                    if obj.quietRun>=3
                        if obj.RecoveryMode==2
                            obj.recoveryPhase=2;
                        else
                            obj.recoveryPhase=3; % quarantine-only hold
                        end
                    end
                else
                    obj.quietRun=0;
                end
            end
            if obj.RecoveryMode==2 && obj.recoveryPhase==2
                % Explicit verifiable bound relative to a PREATTACK checkpoint.
                % No clean shadow, attack flags or theta_star are read here.
                obj.theta=obj.checkpointTheta+0.5*(obj.theta-obj.checkpointTheta);
                adaptAccepted=false;
                if norm(obj.theta-obj.checkpointTheta,2)<=1e-3
                    obj.theta=obj.checkpointTheta;
                    obj.recoveryPhase=3;
                end
            end
            if obj.recoveryPhase==3
                obj.theta=thetaBefore;
                if obj.RecoveryMode==2, obj.theta=obj.checkpointTheta; end
                adaptAccepted=false;
            end
        end
        % Non-oracle, isolated online learner: never reads offline cleanShadow,
        % synthetic provenance labels or attack start/end flags. During high
        % report scatter it uses only the consensus cluster; while clear it
        % uses all received clients. This is an *estimated* clean stream, not
        % ground-truth reconstruction. The offline clean shadow above is
        % maintained separately and only evaluated by the audit.
        evResidual=sqrt(sum((evidence-evMedian).^2,1));
        inlier=evResidual<=0.35;
        obj.inlierCount=sum(inlier);
        if ~obj.alarmLatched && ~reportSuspicious
            % Match deployed dynamics throughout normal commissioning.
            obj.teacherTheta=obj.theta;
            obj.teacherBelief=beliefNow;
            obj.teacherLegacy=0.72*obj.teacherLegacy+0.20*obsReceived+ ...
                0.08*mean(evidence,2);
            obj.teacherAccepted=adaptAccepted;
            obj.teacherGate=gateAllowed;
        elseif obj.inlierCount >= nClients-f
            % A majority-consistency condition is necessary, not sufficient:
            % coherent malicious reports could fool this online teacher.
            eSafe=evidence(:,inlier);
            uSafe=updates(:,inlier);
            wSafe=zeros(1,size(eSafe,2));
            weightedSafe=zeros(size(eSafe));
            for jj=1:size(eSafe,2)
                rr=norm(eSafe(:,jj)-obj.teacherBelief,2);
                wSafe(jj)=1/(1+(rr/max(obj.cfg.patbu.residual_scale,1e-9))^2);
                weightedSafe(:,jj)=wSafe(jj)*eSafe(:,jj);
            end
            % Match the clean-shadow f=2 operator whenever at least 5 reports remain;
            % this still does not reveal missing honest/malicious counterfactuals.
            fSafe=min(f,floor((size(eSafe,2)-1)/2));
            kSafe=obj.trimmedMean(weightedSafe,fSafe);
            bSafe=obj.cfg.patbu.lambda_b*obj.teacherBelief + ...
                obj.cfg.patbu.obs_gain*obsReceived + obj.cfg.patbu.knowledge_gain*kSafe;
            bSafe=min(max(bSafe,-2),2);
            trustSafe=min(max(mean(wSafe),0),1);
            gSafe=obj.robustAggregate(uSafe,fSafe,obj.cfg.common_support_k);
            ng=norm(gSafe,2);
            if ng>obj.cfg.adaptation.clip_norm
                gSafe=gSafe*(obj.cfg.adaptation.clip_norm/ng);
            end
            dSafe=-obj.cfg.adaptation.eta*trustSafe*gSafe;
            nd=norm(dSafe,2);
            if nd>trustRegion, dSafe=dSafe*(trustRegion/nd); end
            candidateSafe=obj.teacherTheta+dSafe;
            pSafe=-0.20*(obj.Bn')*bSafe+1.5*obj.teacherTheta;
            pSafe=obj.clipVec(pSafe,obj.cfg.action_limit);
            predSafe=bSafe+obj.Bn*pSafe;
            legacySafeNext=0.72*obj.teacherLegacy+0.20*obsReceived+ ...
                0.08*mean(eSafe,2);
            % Match the original clean-shadow belief-vs-legacy innovation,
            % without accessing the offline shadow belief or malicious labels.
            riskSafe=0.62*max(0,max(abs(predSafe))-0.85) + ...
                0.16*max(0,max(abs(bSafe))-obj.cfg.normalized_recovery_limit) + ...
                0.14*min(1,norm(bSafe-legacySafeNext,2)) + 0.08*(1-trustSafe);
            obj.teacherGate=(riskSafe<=rhoMax-obj.cfg.gate.risk_margin) && (trustSafe>=qMin);
            acceptedSafe=obj.teacherGate && ...
                norm(bSafe,2)+0.08*norm(candidateSafe,2) <= ...
                norm(bSafe,2)+0.08*norm(obj.teacherTheta,2)+ ...
                obj.cfg.adaptation.validation_slack;
            if acceptedSafe, obj.teacherTheta=candidateSafe; end
            obj.teacherAccepted=acceptedSafe;
            obj.teacherBelief=bSafe;
            obj.teacherLegacy=legacySafeNext;
        else
            obj.teacherAccepted=false; obj.teacherGate=false;
        end

        if obj.RecoveryMode==3 && obj.checkpointValid && obj.alarmLatched
            if reportSuspicious
                obj.recoveryPhase=1; obj.quietRun=0;
            elseif obj.recoveryPhase==1
                obj.quietRun=obj.quietRun+1;
                if obj.quietRun>=3, obj.recoveryPhase=2; end
            end
            % First survive at the isolated commissioning checkpoint, then
            % gradually track the independently learned online clean proxy.
            % The proxy is not the offline evaluation shadow.
            if obj.recoveryPhase==1
                obj.theta=obj.checkpointTheta;
                adaptAccepted=false;
            elseif obj.recoveryPhase>=2
                % Discard speculative base-TGOPA deployment; recovery applies
                % only an approved bounded step toward the online proxy.
                obj.theta=thetaBefore;
                if ~reportSuspicious && obj.teacherGate && gateAllowed
                    errSafe=obj.teacherTheta-obj.theta;
                    dFollow=0.25*errSafe;
                    dNorm=norm(dFollow,2);
                    if dNorm>0.01, dFollow=dFollow*(0.01/dNorm); end
                    obj.theta=obj.theta+dFollow;
                    adaptAccepted=norm(dFollow,2)>1e-12;
                    if norm(obj.theta-obj.teacherTheta,2)<=1e-3
                        obj.recoveryPhase=3;
                    else
                        obj.recoveryPhase=2;
                    end
                else
                    adaptAccepted=false;
                end
            end
        end
        obj.lastRollback=norm(obj.theta-thetaBefore,2);

        % The shadow sees the SAME actual physical observation trajectory,
        % and clean reports reconstructed solely for OFFLINE evaluation.
        % It never feeds the active controller, physical actuators, or Gate.
        % No known optimal target or artificial contraction is inserted.
        if mc==1
            aggShadow=mean(cleanUpdates,2);
        else
            aggShadow=obj.robustAggregate(cleanUpdates,f,obj.cfg.common_support_k);
        end
        obj.legacyShadow=0.72*obj.legacyShadow + 0.20*zPhysical + 0.08*mean(cleanEvidence,2);
        if any(mc==[1 2 3])
            bShadow=zPhysical; trustShadow=0.5;
        else
            weightsShadow=zeros(1,nClients); wShadow=zeros(4,nClients);
            for cj=1:nClients
                rShadow=norm(cleanEvidence(:,cj)-obj.beliefShadow,2);
                weightsShadow(cj)=1/(1+(rShadow/max(obj.cfg.patbu.residual_scale,1e-9))^2);
                wShadow(:,cj)=weightsShadow(cj)*cleanEvidence(:,cj);
            end
            kShadow=obj.trimmedMean(wShadow,f);
            bShadow=obj.cfg.patbu.lambda_b*obj.beliefShadow + ...
                obj.cfg.patbu.obs_gain*zPhysical + obj.cfg.patbu.knowledge_gain*kShadow;
            bShadow=min(max(bShadow,-2),2);
            obj.beliefShadow=bShadow;
            trustShadow=min(max(mean(weightsShadow),0),1);
        end
        pShadow=-0.20*(obj.Bn')*bShadow+1.5*obj.thetaShadow;
        pShadow=obj.clipVec(pShadow,obj.cfg.action_limit);
        predShadow=bShadow+obj.Bn*pShadow;
        bs=max(0,max(abs(predShadow))-0.85);
        br=max(0,max(abs(bShadow))-obj.cfg.normalized_recovery_limit);
        bu=min(1,norm(bShadow-obj.legacyShadow,2));
        riskShadow=0.62*bs+0.16*br+0.14*bu+0.08*(1-trustShadow);
        gateShadow=(riskShadow<=rhoMax-obj.cfg.gate.risk_margin) && trustShadow>=qMin;
        if any(mc==[1 2 4]), gateShadow=true; end
        thetaShadowBefore=obj.thetaShadow;
        gg=aggShadow; gnShadow=norm(gg,2);
        if gnShadow>obj.cfg.adaptation.clip_norm
            gg=gg*(obj.cfg.adaptation.clip_norm/gnShadow);
        end
        deltaShadow=-obj.cfg.adaptation.eta*trustShadow*gg;
        if norm(deltaShadow,2)>trustRegion
            deltaShadow=deltaShadow*(trustRegion/norm(deltaShadow,2));
        end
        candidateShadow=obj.thetaShadow+deltaShadow;
        vBefore=norm(bShadow,2)+0.08*norm(obj.thetaShadow,2);
        vAfter=norm(bShadow,2)+0.08*norm(candidateShadow,2);
        acceptedShadow=trustShadow>=qMin && gateShadow && ...
            vAfter<=vBefore+obj.cfg.adaptation.validation_slack;
        if any(mc==[1 2 5])
            obj.thetaShadow=obj.thetaShadow-0.12*aggShadow;
            acceptedShadow=true;
        elseif acceptedShadow
            obj.thetaShadow=candidateShadow;
        end
        policyDrift=norm(obj.theta,2);

        if any(mc==[1 2 6])
            uShield=obj.clipVec(proposal,obj.cfg.action_limit);
            predShield=beliefNow+obj.Bn*uShield;
            intervention=0;
        else
            [uShield,intervention,predShield]=obj.projectShield(beliefNow,proposal);
        end
        minMargin=obj.cfg.normalized_safe_limit-max(abs(predShield));

        uPost=zeros(4,1);
        if physicalActive
            uPost=attackScale*obj.cfg.post_shield_control_attack*obj.detNoise(t,211);
        end
        diagOut=[trust;risk;double(gateAllowed);beliefDist;policyDrift;intervention; ...
            minMargin;double(attackActive);double(dangerous);double(adaptAccepted); ...
            obj.theta; obj.thetaShadow; double(acceptedShadow); ...
            trustShadow; double(gateShadow); norm(obj.theta-thetaBefore,2); ...
            norm(obj.thetaShadow-thetaShadowBefore,2); ...
            reportScatter; double(obj.alarmLatched); double(obj.recoveryPhase); ...
            obj.checkpointTheta; norm(obj.theta-obj.checkpointTheta,2); ...
            obj.lastRollback; double(obj.checkpointValid); ...
            obj.teacherTheta; norm(obj.theta-obj.teacherTheta,2); ...
            double(obj.teacherAccepted); double(obj.inlierCount)];
        obj.stepCount=obj.stepCount+1;
    end

