    end

    function loadObjectImpl(obj,s,wasLocked)
        if isfield(s,'cfg'), obj.cfg=s.cfg; end
        if isfield(s,'mapping'), obj.mapping=s.mapping; end
        if isfield(s,'B'), obj.B=s.B; end
        if isfield(s,'Bn'), obj.Bn=s.Bn; end
        if isfield(s,'center'), obj.center=s.center; end
        if isfield(s,'scale'), obj.scale=s.scale; end
        if isfield(s,'belief'), obj.belief=s.belief; end
        if isfield(s,'cleanBelief'), obj.cleanBelief=s.cleanBelief; end
        if isfield(s,'theta'), obj.theta=s.theta; end
        if isfield(s,'stepCount'), obj.stepCount=s.stepCount; end
        if isfield(s,'thetaShadow'), obj.thetaShadow=s.thetaShadow; end
        if isfield(s,'beliefShadow'), obj.beliefShadow=s.beliefShadow; end
        if isfield(s,'legacyShadow'), obj.legacyShadow=s.legacyShadow; end
        if isfield(s,'checkpointTheta'), obj.checkpointTheta=s.checkpointTheta; end
        if isfield(s,'checkpointValid'), obj.checkpointValid=s.checkpointValid; end
        if isfield(s,'alarmLatched'), obj.alarmLatched=s.alarmLatched; end
        if isfield(s,'quietRun'), obj.quietRun=s.quietRun; end
        if isfield(s,'recoveryPhase'), obj.recoveryPhase=s.recoveryPhase; end
        if isfield(s,'lastRollback'), obj.lastRollback=s.lastRollback; end
        if isfield(s,'teacherTheta'), obj.teacherTheta=s.teacherTheta; end
        if isfield(s,'teacherBelief'), obj.teacherBelief=s.teacherBelief; end
        if isfield(s,'teacherLegacy'), obj.teacherLegacy=s.teacherLegacy; end
        if isfield(s,'teacherAccepted'), obj.teacherAccepted=s.teacherAccepted; end
        if isfield(s,'teacherGate'), obj.teacherGate=s.teacherGate; end
        if isfield(s,'inlierCount'), obj.inlierCount=s.inlierCount; end
        loadObjectImpl@matlab.System(obj,s,wasLocked);
        obj.ensureRuntimeState();
    end
end

methods(Access=private)
    function loadRuntimeConfig(obj)
        obj.cfg=jsondecode(fileread(obj.ConfigPath));
        obj.mapping=jsondecode(fileread(obj.MappingPath));
        assert(isstruct(obj.cfg),'AEFC:NativeConfig','Decoded native configuration must be a structure.');
        assert(isstruct(obj.mapping) && isfield(obj.mapping,'validated') && logical(obj.mapping.validated), ...
            'AEFC:NativeMapping','Native IEEE39 mapping is not validated.');
        obj.B=double(obj.mapping.sensitivity_matrix);
        obj.center=double(obj.mapping.baseline_observation(:));
        assert(numel(obj.center)==4 && isequal(size(obj.B),[4 4]), ...
            'AEFC:NativeDimension','Expected validated 4x4 native mapping.');
        obj.scale=obj.deriveScale(obj.mapping.observation_edges,obj.center);
        obj.Bn=diag(1./obj.scale)*obj.B;
    end

    function resetRuntimeState(obj)
        obj.belief=zeros(4,1); obj.cleanBelief=zeros(4,1);
        obj.theta=zeros(4,1); obj.stepCount=0;
        obj.thetaShadow=zeros(4,1); obj.beliefShadow=zeros(4,1); obj.legacyShadow=zeros(4,1);
        obj.checkpointTheta=zeros(4,1); obj.checkpointValid=false; obj.alarmLatched=false;
        obj.quietRun=0; obj.recoveryPhase=0; obj.lastRollback=0;
        obj.teacherTheta=zeros(4,1); obj.teacherBelief=zeros(4,1);
        obj.teacherLegacy=zeros(4,1); obj.teacherAccepted=false;
        obj.teacherGate=false; obj.inlierCount=0;
    end

    function ensureRuntimeState(obj)
        cfgOK=isstruct(obj.cfg) && isfield(obj.cfg,'attack_start_step') && isfield(obj.cfg,'patbu');
        mapOK=isstruct(obj.mapping) && isfield(obj.mapping,'validated');
        dynOK=isnumeric(obj.Bn) && isequal(size(obj.Bn),[4 4]) && ...
              isnumeric(obj.center) && numel(obj.center)==4 && ...
              isnumeric(obj.scale) && numel(obj.scale)==4;
        if ~(cfgOK && mapOK && dynOK), obj.loadRuntimeConfig(); end
        if ~isnumeric(obj.belief) || numel(obj.belief)~=4, obj.belief=zeros(4,1); end
        if ~isnumeric(obj.cleanBelief) || numel(obj.cleanBelief)~=4, obj.cleanBelief=zeros(4,1); end
        if ~isnumeric(obj.theta) || numel(obj.theta)~=4, obj.theta=zeros(4,1); end
        if ~isnumeric(obj.stepCount) || ~isscalar(obj.stepCount) || ~isfinite(obj.stepCount), obj.stepCount=0; end
        if ~isnumeric(obj.thetaShadow) || numel(obj.thetaShadow)~=4, obj.thetaShadow=zeros(4,1); end
        if ~isnumeric(obj.beliefShadow) || numel(obj.beliefShadow)~=4, obj.beliefShadow=zeros(4,1); end
        if ~isnumeric(obj.legacyShadow) || numel(obj.legacyShadow)~=4, obj.legacyShadow=zeros(4,1); end
        if ~isnumeric(obj.checkpointTheta) || numel(obj.checkpointTheta)~=4, obj.checkpointTheta=zeros(4,1); end
        if isempty(obj.checkpointValid), obj.checkpointValid=false; end
        if isempty(obj.alarmLatched), obj.alarmLatched=false; end
        if isempty(obj.quietRun), obj.quietRun=0; end
        if isempty(obj.recoveryPhase), obj.recoveryPhase=0; end
        if isempty(obj.lastRollback), obj.lastRollback=0; end
        if isempty(obj.teacherTheta) || numel(obj.teacherTheta)~=4, obj.teacherTheta=zeros(4,1); end
        if isempty(obj.teacherBelief) || numel(obj.teacherBelief)~=4, obj.teacherBelief=zeros(4,1); end
        if isempty(obj.teacherLegacy) || numel(obj.teacherLegacy)~=4, obj.teacherLegacy=zeros(4,1); end
        if isempty(obj.teacherAccepted), obj.teacherAccepted=false; end
        if isempty(obj.teacherGate), obj.teacherGate=false; end
        if isempty(obj.inlierCount), obj.inlierCount=0; end
    end

    function [physical,knowledge]=scenarioFlags(~,s)
        physical=(s==3 || s==4); knowledge=(s==2 || s==4);
    end

    function v=detNoise(obj,t,salt)
        idx=(1:4)';
        v=sin((idx+salt)*(t+1)*0.731 + (double(obj.Seed)+1)*0.193 + salt*0.017);
        n=norm(v,inf); if n>0, v=v/n; end
    end

    function m=trimmedMean(~,X,f)
        xs=sort(X,2); n=size(xs,2);
        if 2*f>=n, error('AEFC:TrimBudget','Invalid trim budget.'); end
        if f>0, xs=xs(:,f+1:n-f); end
        m=mean(xs,2);
    end

    function agg=robustAggregate(obj,X,f,k)
        med=median(X,2); [~,ord]=sort(abs(med),'descend');
        k=max(1,min(k,numel(med))); support=ord(1:k);
        agg=zeros(4,1); agg(support)=obj.trimmedMean(X(support,:),f);
    end

    function [u,intervention,pred]=projectShield(obj,z,u0)
        u=obj.clipVec(u0,obj.cfg.action_limit);
        reserve=obj.cfg.shield_reserve;
        safe=max(0.05,obj.cfg.normalized_safe_limit-reserve);
        for iter=1:3
            pred=z+obj.Bn*u; target=min(max(pred,-safe),safe);
            if max(abs(pred)-safe)<=1e-9, break; end
            du=pinv(obj.Bn)*(target-pred);
            u=obj.clipVec(u+du,obj.cfg.action_limit);
        end
        pred=z+obj.Bn*u; intervention=norm(u-u0,2);
    end

    function v=clipVec(~,v,lim)
        v=min(max(v,-lim),lim);
    end

    function s=deriveScale(~,edges,center)
        s=zeros(4,1);
        for i=1:4
            reason=''; try, reason=lower(edges(i).observation_reason); catch, end
            if contains(reason,'rotor-speed'), s(i)=0.02;
            elseif contains(reason,'terminal-voltage'), s(i)=0.10;
            elseif contains(reason,'rotor-angle'), s(i)=0.35;
            else, s(i)=max(0.02,0.10*max(abs(center(i)),1e-3)); end
        end
    end
